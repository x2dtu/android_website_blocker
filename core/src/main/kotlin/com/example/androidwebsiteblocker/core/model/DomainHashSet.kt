package com.example.androidwebsiteblocker.core.model

import java.io.DataInputStream
import java.io.InputStream

/**
 * A large domain list (~1M entries) stored compactly as sorted 64-bit FNV-1a hashes: ~8 bytes per
 * domain instead of a string set that would need over 100 MB. A host matches if it or any parent
 * domain is in the list (old.example.com → example.com). Hash collisions are possible in theory
 * but negligible at this size (~1 in 10^13 per lookup).
 *
 * File format (big-endian): magic "NBDS", int version (1), int count, then [count] longs sorted
 * as signed values. Generated by tools/build_domain_list.py.
 */
class DomainHashSet(private val sortedHashes: LongArray) {

    val size: Int get() = sortedHashes.size

    fun containsHostOrParent(host: String): Boolean {
        val h = host.trim().lowercase().trimEnd('.')
        if (h.isEmpty()) return false
        var start = 0
        while (true) {
            val suffix = h.substring(start)
            if (!suffix.contains('.')) return false // don't match bare TLDs like "com"
            if (sortedHashes.binarySearch(fnv1a64(suffix)) >= 0) return true
            val nextDot = h.indexOf('.', start)
            if (nextDot < 0) return false
            start = nextDot + 1
        }
    }

    companion object {
        private const val MAGIC = 0x4E424453 // "NBDS"

        fun read(input: InputStream): DomainHashSet {
            val data = DataInputStream(input.buffered(1 shl 16))
            require(data.readInt() == MAGIC) { "Not a domain list file" }
            require(data.readInt() == 1) { "Unsupported domain list version" }
            val count = data.readInt()
            val hashes = LongArray(count) { data.readLong() }
            return DomainHashSet(hashes)
        }

        /** FNV-1a, 64-bit, over the UTF-8 bytes. Must match tools/build_domain_list.py. */
        fun fnv1a64(s: String): Long {
            var hash = -0x340d631b7bdddcdbL // 0xcbf29ce484222325
            for (b in s.encodeToByteArray()) {
                hash = hash xor (b.toLong() and 0xff)
                hash *= 0x100000001b3L
            }
            return hash
        }
    }
}

/**
 * The bundled adult-site list, loaded once by the app at startup. Until it's loaded (a moment
 * after launch), nothing matches.
 */
object AdultSites {
    @Volatile var list: DomainHashSet? = null

    fun contains(host: String): Boolean = list?.containsHostOrParent(host) == true
}
